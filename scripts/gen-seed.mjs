// Regenerates migrations/0002_seed_catalog.sql from catalog/catalog.json.
// Run with: node scripts/gen-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";

const catalog = JSON.parse(readFileSync(new URL("../catalog/catalog.json", import.meta.url), "utf8"));
const q = (v) => (v === undefined || v === null ? "NULL" : "'" + String(v).replace(/'/g, "''") + "'");
const j = (v) => (v === undefined ? "NULL" : q(JSON.stringify(v)));

const rows = catalog.items.map((it) =>
  `(${q(it.id)}, ${q(it.section)}, 'catalog', ${q(it.name)}, ${it.tier ?? "NULL"}, ${q(it.material)}, ${j(it.materials)}, ${j(it.appliesTo)}, ${j(it.effects)}, ${j(it.categories)}, ${q(it.notes)}, ${q(catalog.version)})`
);

const sql = [
  "-- Generated by scripts/gen-seed.mjs from catalog/catalog.json. Do not edit by hand.",
  "INSERT INTO items (id, section_id, source, name, tier, material, materials, applies_to, effects, categories, notes, catalog_version) VALUES",
  rows.join(",\n") + ";",
  "INSERT INTO item_state (item_id) SELECT id FROM items;",
  `INSERT INTO settings (key, value) VALUES ('catalog_version', ${q(catalog.version)});`,
  "",
].join("\n");

writeFileSync(new URL("../migrations/0002_seed_catalog.sql", import.meta.url), sql);
console.log(`Wrote ${catalog.items.length} items for catalog ${catalog.version}`);
